public class Mekanik {
    private String nama;
    private String keahlian;

    // Konstruktor
    public Mekanik(String nama, String keahlian) {
        this.nama = nama;
        this.keahlian = keahlian;
    }

    // Getter
    public String getNama() {
        return nama;
    }

    public String getKeahlian() {
        return keahlian;
    }
}
