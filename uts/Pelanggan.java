public class Pelanggan {
    private String nik;
    private String nama;

    // Konstruktor
    public Pelanggan(String nik, String nama) {
        this.nik = nik;
        this.nama = nama;
    }

    //Getter
    public String getNik() {
        return nik;
    }

    public String getNama() {
        return nama;
    }
}
